"""Send one preprocessed 28x28 MNIST image to ml_demo_top over UART.

Protocol: write exactly 784 raw uint8 pixel bytes; read one raw result byte 0..9.
Example (from image_processing):
    python send_digit_uart.py --port COM4 --image digit_output/sent_image.bin
"""
from __future__ import annotations

import argparse
from pathlib import Path
import time

import serial


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--port", default="COM4", help="serial port, e.g. COM4")
    parser.add_argument("--baud", type=int, default=115200)
    parser.add_argument(
        "--image",
        type=Path,
        default=Path("digit_output/sent_image.bin"),
        help="raw 784-byte image generated by draw_app.py",
    )
    parser.add_argument("--timeout", type=float, default=5.0)
    args = parser.parse_args()

    if not args.image.exists():
        raise FileNotFoundError(f"Image file not found: {args.image}")
    payload = args.image.read_bytes()
    if len(payload) != 784:
        raise ValueError(
            f"Expected exactly 784 raw pixel bytes in {args.image}; got {len(payload)}"
        )

    with serial.Serial(
        port=args.port,
        baudrate=args.baud,
        timeout=args.timeout,
        write_timeout=args.timeout,
    ) as ser:
        # Give the UART interface a moment to settle after opening the port.
        time.sleep(0.05)
        ser.reset_input_buffer()
        written = ser.write(payload)
        ser.flush()
        if written != len(payload):
            raise IOError(f"UART wrote {written} of {len(payload)} bytes")

        response = ser.read(1)
        if len(response) != 1:
            raise TimeoutError(
                "No prediction byte received. Check bitstream, UART pins/baud, "
                "memory initialization, and that the FPGA finished inference."
            )

    digit = response[0]
    if digit > 9:
        raise ValueError(
            f"Received 0x{digit:02X}, expected a raw digit byte from 0 through 9"
        )
    print(f"Sent {len(payload)} image bytes")
    print(f"FPGA predicted digit: {digit}")


if __name__ == "__main__":
    main()
